// Fetches DSB's public shelters from Geonorge and writes src/shelters-data.ts.
//
//   node packages/core/scripts/update-shelters.mjs
//
// The data is DSB's «Tilfluktsrom – offentlige» (NLOD, credit DSB), rebuilt every night on
// Geonorge. The WFS is asked for latitude and longitude (EPSG:4326), so the phone gets a finished
// list. It only speaks GML, but the features are flat, so a few patterns read them.
import { writeFileSync } from 'node:fs';

const WFS =
  'https://wfs.geonorge.no/skwms1/wfs.tilfluktsrom_offentlige?service=WFS&version=2.0.0&request=GetFeature' +
  '&typeNames=app:Tilfluktsrom&srsName=urn:ogc:def:crs:EPSG::4326';
const OUT = new URL('../src/shelters-data.ts', import.meta.url);

/** The text of the first `<app:name>` in a feature, with XML entities decoded. */
function field(xml, name) {
  const match = xml.match(new RegExp(`<app:${name}>([^<]*)</app:${name}>`));
  if (!match) return '';
  return match[1]
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, '&');
}

/** «Trimv. 09 - Borre Idrettspark (off)» → «Trimv. 09 - Borre Idrettspark»: every row is public. */
const cleanAddress = (address) =>
  address
    .replace(/\s*\(off\.?\)\s*$/i, '')
    .replace(/\s+/g, ' ')
    .trim();

const response = await fetch(WFS);
if (!response.ok) throw new Error(`${WFS}: ${response.status}`);
const gml = await response.text();

let extracted = '';
const rows = [...gml.matchAll(/<app:Tilfluktsrom\b[\s\S]*?<\/app:Tilfluktsrom>/g)]
  .map(([xml]) => {
    const pos = xml.match(/<gml:pos>\s*([-\d.]+)\s+([-\d.]+)\s*<\/gml:pos>/);
    if (!pos) return null;
    extracted ||= field(xml, 'datauttaksdato').slice(0, 10);
    return {
      id: field(xml, 'lokalId'),
      // EPSG:4326 in GML is latitude first.
      lat: Math.round(Number(pos[1]) * 1e5) / 1e5,
      lon: Math.round(Number(pos[2]) * 1e5) / 1e5,
      places: Number(field(xml, 'plasser')) || 0,
      room: field(xml, 'romnr'),
      address: cleanAddress(field(xml, 'adresse')),
    };
  })
  .filter((row) => row && row.id)
  .sort((a, b) => a.id.localeCompare(b.id));

// A broken or empty answer must never replace a good list.
if (rows.length < 400) throw new Error(`Only ${rows.length} shelters in the answer; keeping the old list`);

const body = rows
  .map((r) => `  [${JSON.stringify(r.id)}, ${r.lat}, ${r.lon}, ${r.places}, ${JSON.stringify(r.room)}, ${JSON.stringify(r.address)}],`)
  .join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/update-shelters.mjs. Don't edit by hand.
// Source: DSB, «Tilfluktsrom – offentlige» from Geonorge, NLOD (https://data.norge.no/nlod/no/1.0).

/** The date DSB's data was extracted, YYYY-MM-DD. */
export const SHELTERS_UPDATED = '${extracted}';

/** id, latitude, longitude, places, room number, address. */
export const SHELTER_ROWS: readonly (readonly [string, number, number, number, string, string])[] = [
${body}
];
`,
);
console.log(`${rows.length} shelters, ${rows.reduce((sum, r) => sum + r.places, 0)} places, extracted ${extracted}`);
